<?php

namespace Tests\Feature\Registry;

use App\Enums\AuditEventType;
use App\Enums\UserRole;
use App\Models\AuditEvent;
use App\Models\MigrantRegistryEntry;
use App\Models\User;
use App\Services\Auth\Base64UrlService;
use App\Services\Security\Encryption\AccessGrantCrypto;
use App\Services\Security\Encryption\EnvelopeCipher;
use App\Services\Security\Encryption\KekProvider;
use App\Services\Security\Encryption\KeyFile;
use App\Services\Security\Encryption\RegistryUserKeys;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Tests\TestCase;

/**
 * registry:keys-trace must prove, from the stored data, that keys were generated and registered, that every sealed box
 * came from its own X25519 Diffie-Hellman exchange, and that temporary accesses carry valid signatures, and it must
 * flag tampering.
 */
class RegistryKeysTraceTest extends TestCase
{
    use RefreshDatabase;

    private string $dir;

    private User $coordinator;

    private string $keyFile;

    protected function setUp(): void
    {
        parent::setUp();
        $this->dir = storage_path('framework/testing/registry-trace-'.bin2hex(random_bytes(4)));
        File::ensureDirectoryExists($this->dir);

        // Domain keys generated by the real command; .env gets exactly the public keys it logged.
        $this->artisan('registry:keys-init', ['--private-dir' => $this->dir, '--plain' => true])->assertSuccessful();
        $logged = AuditEvent::query()->where('event_type', AuditEventType::RegistryDomainKeysGenerated->value)->firstOrFail()->metadata['publicKeys'];
        config([
            'registry_encryption.enabled' => true,
            'registry_encryption.write_plaintext' => false,
            'registry_encryption.public_keys' => [
                'cand' => ['id' => 'pk:cand-1', 'public' => $logged['pk:cand-1']],
                'proc' => ['id' => 'pk:proc-1', 'public' => $logged['pk:proc-1']],
            ],
        ]);
        app()->forgetInstance(KekProvider::class);
        app()->forgetInstance(EnvelopeCipher::class);

        $this->coordinator = User::factory()->create(['role' => UserRole::Coordinator->value]);
        $keyFile = KeyFile::create('una-frase-larga-de-prueba');
        $this->keyFile = $keyFile['file'];
        app(RegistryUserKeys::class)->enroll($this->coordinator, $keyFile, 'test');
        $this->artisan('registry:keys-grant', [
            'email' => $this->coordinator->email, '--private-dir' => $this->dir, '--fingerprint' => $keyFile['fingerprint'],
        ])->assertSuccessful();
    }

    protected function tearDown(): void
    {
        File::deleteDirectory($this->dir);
        parent::tearDown();
    }

    public function test_it_proves_one_diffie_hellman_per_sealed_box_and_valid_signatures(): void
    {
        $entries = collect(range(1, 3))->map(fn (int $i): MigrantRegistryEntry => $this->entry("Persona {$i}"));
        $grantId = $this->signedAccess($entries->first());

        $report = $this->trace();

        $this->assertSame([true, true], array_column($report['domainKeys'], 'matchesLoggedKey'));
        $this->assertNotNull($report['domainKeys'][0]['generationLogged']);
        $this->assertTrue($report['userKeys'][0]['fingerprintValid']);

        // Two domain keys delivered to the coordinator: two sealed boxes, two ephemeral keys.
        $this->assertSame(['sealedBoxes' => 2, 'distinctEphemeralKeys' => 2, 'oneExchangePerBox' => true],
            array_intersect_key($report['keyGrants']['diffieHellman'], array_flip(['sealedBoxes', 'distinctEphemeralKeys', 'oneExchangePerBox'])));

        $this->assertSame(3, $report['envelopes']['total']);
        $this->assertSame(['pk:cand-1' => 3], $report['envelopes']['byKekId']);
        $this->assertSame(0, $report['envelopes']['unexpectedFormat']);
        $this->assertTrue($report['envelopes']['diffieHellman']['oneExchangePerBox']);
        $this->assertSame(3, $report['envelopes']['diffieHellman']['distinctEphemeralKeys']);

        $this->assertSame(1, $report['operatorAccess']['signaturesValid']);
        $this->assertSame([], $report['operatorAccess']['signaturesInvalid']);
        $this->assertSame(0, Artisan::call('registry:keys-trace'));

        // Tampering: a changed wrapped key breaks the signature, a copied envelope reuses an ephemeral key.
        DB::table('registry_access_grants')->where('id', $grantId)->update(['wrapped_deks' => '{"registration_payload":"x"}']);
        $copied = DB::table('migrant_registry_entries')->where('id', $entries[1]->id)->value('payload_json_enc');
        DB::table('migrant_registry_entries')->where('id', $entries[2]->id)->update(['payload_json_enc' => $copied]);

        $report = $this->trace();
        $this->assertSame([$grantId], $report['operatorAccess']['signaturesInvalid']);
        $this->assertFalse($report['envelopes']['diffieHellman']['oneExchangePerBox']);
        $this->assertSame(1, Artisan::call('registry:keys-trace'));
    }

    public function test_opening_an_operator_session_key_is_audited(): void
    {
        $operator = $this->enrolled(UserRole::NonCoordinator);

        $fingerprint = $this->actingAs($operator)->getJson('/registry/access/mine')->assertOk()->json('data.fingerprint');

        $event = AuditEvent::query()->where('event_type', AuditEventType::RegistryKeysSessionGenerated->value)->firstOrFail();
        $this->assertSame($operator->id, $event->actor_user_id);
        $this->assertSame($fingerprint, $event->metadata['fingerprint']);
        $this->assertSame('X25519', $event->metadata['algorithm']);
        $this->assertSame(
            DB::table('registry_access_sessions')->where('user_id', $operator->id)->value('public_key'),
            $event->metadata['publicKey'],
        );
    }

    public function test_key_deliveries_record_the_key_agreement_used(): void
    {
        $event = AuditEvent::query()->where('event_type', AuditEventType::RegistryKeysGranted->value)->firstOrFail();

        $this->assertStringContainsString('X25519', $event->metadata['keyAgreement']);
        $this->assertCount(2, $event->metadata['grantIds']);
    }

    /** @return array<string, mixed> */
    private function trace(): array
    {
        Artisan::call('registry:keys-trace', ['--json' => true]);

        return json_decode(Artisan::output(), true, flags: JSON_THROW_ON_ERROR);
    }

    private function entry(string $name): MigrantRegistryEntry
    {
        return MigrantRegistryEntry::query()->create([
            'created_by' => $this->coordinator->id,
            'created_by_role' => 'volunteer',
            'current_status' => 'pending_review',
            'payload_json' => ['fullName' => $name],
        ]);
    }

    /** A granted temporary access exactly as AccessGrantService::grant() stores it. */
    private function signedAccess(MigrantRegistryEntry $entry): int
    {
        $operator = User::factory()->create(['role' => UserRole::NonCoordinator->value]);
        $session = sodium_crypto_box_keypair();
        $sessionPublic = sodium_crypto_box_publickey($session);
        $sessionId = DB::table('registry_access_sessions')->insertGetId([
            'user_id' => $operator->id, 'session_hash' => hash('sha256', 'session'), 'public_key' => base64_encode($sessionPublic),
            'fingerprint' => KeyFile::fingerprint($sessionPublic), 'expires_at' => now()->addHour(), 'created_at' => now(), 'updated_at' => now(),
        ]);
        $wrapped = json_encode(['registration_payload' => AccessGrantCrypto::wrapDek(random_bytes(32), 'aad', $sessionPublic)]);
        $expires = now()->addMinutes(30)->format('Y-m-d H:i:s');
        $id = DB::table('registry_access_grants')->insertGetId([
            'user_id' => $operator->id, 'session_id' => $sessionId, 'resource_type' => 'registry', 'resource_id' => $entry->id,
            'status' => 'requested', 'created_at' => now(), 'updated_at' => now(),
        ]);
        $signature = AccessGrantCrypto::sign(AccessGrantCrypto::payload([
            'id' => $id, 'resource_type' => 'registry', 'resource_id' => $entry->id, 'user_id' => $operator->id,
            'sessionPublic' => $sessionPublic, 'expires_at' => $expires, 'signed_by' => $this->coordinator->id, 'wrapped_deks' => $wrapped,
        ]), KeyFile::open($this->keyFile, 'una-frase-larga-de-prueba')['sign']);

        DB::table('registry_access_grants')->where('id', $id)->update([
            'status' => 'granted', 'wrapped_deks' => $wrapped, 'signed_by' => $this->coordinator->id,
            'signature' => $signature, 'expires_at' => $expires, 'decided_at' => now(),
        ]);

        return $id;
    }

    private function enrolled(UserRole $role): User
    {
        $user = User::factory()->create(['role' => $role->value, 'two_factor_enabled' => true, 'two_factor_secret' => 'JBSWY3DPEHPK3PXP']);
        $user->webauthnCredentials()->create([
            'credential_id' => app(Base64UrlService::class)->encode(random_bytes(16)),
            'public_key' => app(Base64UrlService::class)->encode(random_bytes(48)),
            'public_key_algorithm' => -7,
            'name' => 'Key',
            'transports' => ['usb'],
            'attestation_object' => app(Base64UrlService::class)->encode(random_bytes(32)),
            'client_data_json' => app(Base64UrlService::class)->encode(random_bytes(32)),
        ]);

        return $user;
    }
}
